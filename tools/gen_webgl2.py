#!/usr/bin/env python3
"""Regenerates src/webgl2.esk from web/webgl2.js.

gpu_open evaluates the JavaScript in the page (emscripten_run_script_int), so the
WebGL2 backend needs no build flag or extra file besides gpu-naga.wasm.

Usage: python3 -I tools/gen_webgl2.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "webgl2.js"
OUT = ROOT / "src" / "webgl2.esk"


def literal(line: str) -> str:
    out = []
    for ch in line:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) > 0x7E:
            raise SystemExit(f"web/webgl2.js: keep the file ASCII (found U+{ord(ch):04X})")
        else:
            out.append(ch)
    return '    "' + "".join(out) + '\\n"'


def main() -> None:
    js = SRC.read_text()
    lines = []
    for line in js.splitlines():
        stripped = line.strip()
        # Comment lines stay in web/webgl2.js only.
        if stripped.startswith("//") or not stripped:
            continue
        lines.append(literal(line.rstrip()))
    lines.append('    ";__gpuWebGL2.install()\\n";')
    body = "\n".join(lines)
    OUT.write_text(
        "// webgl2.esk: the WebGL2 backend's JavaScript (web/webgl2.js), generated by\n"
        "// tools/gen_webgl2.py; edit web/webgl2.js and run the script again.\n"
        "//\n"
        "// gpu_open evaluates it in the page: it installs a navigator.gpu that answers\n"
        "// with the browser's WebGPU adapter when there is one and a WebGL2 adapter\n"
        "// otherwise, and evaluates to 1 when either can be had (docs/web.md).\n"
        "\n"
        "#ifdef __EMSCRIPTEN__\n"
        "string _gpu_webgl2_js =\n"
        f"{body}\n"
        "#endif\n"
    )


if __name__ == "__main__":
    main()
